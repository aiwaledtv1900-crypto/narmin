function getShape(name) {
  if (!name) return null;
  // تطبيع
  const n = String(name).trim().replace(/ة$/,'ه');
  if (SHAPES[name]) return { name, ...SHAPES[name] };
  if (SHAPES[n]) return { name: n, ...SHAPES[n] };

  // بحث تقريبي
  const keys = Object.keys(SHAPES);
  for (const k of keys) {
    if (k.includes(name) || name.includes(k)) {
      return { name: k, ...SHAPES[k] };
    }
  }
  return null;
}

function listShapes() {
  return Object.keys(SHAPES).filter(k => !SHAPES[k].transparent);
}

